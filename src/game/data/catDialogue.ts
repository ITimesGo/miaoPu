import type { CatRole } from '../types'

export type DialogueSituation =
  | 'morning_out'
  | 'rain'
  | 'farm_busy'
  | 'harvest'
  | 'soft_idle'

export type DialogueLine = { id: string; text: string }

export type DialoguePool = {
  shared: DialogueLine[]
  byRole?: Partial<Record<CatRole, DialogueLine[]>>
}

function L(id: string, text: string): DialogueLine {
  return { id, text }
}

function lines(prefix: string, texts: string[]): DialogueLine[] {
  return texts.map((text, i) => L(`${prefix}${String(i + 1).padStart(2, '0')}`, text))
}

function pool(
  prefix: string,
  shared: string[],
  byRole?: Partial<Record<CatRole, string[]>>,
): DialoguePool {
  const roles = byRole
    ? (Object.fromEntries(
        Object.entries(byRole).map(([role, texts]) => [
          role,
          lines(`${prefix}_${role}_`, texts ?? []),
        ]),
      ) as Partial<Record<CatRole, DialogueLine[]>>)
    : undefined
  return { shared: lines(`${prefix}_s`, shared), byRole: roles }
}

